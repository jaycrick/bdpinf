"""Subset-driven inference helpers for NTVMR manuscript analysis.

This module provides utilities for splitting the cleaned NTVMR manuscript
DataFrame into the six canonical analysis subsets (non-lectionary combined,
lectionary, and four per-section non-lectionary groups), resampling each
subset independently via the weighted date-range KDE, and fitting a
birth-death process model to each.

The six subsets, in canonical order:

1. ``non_lectionary`` — groups 1–3 (papyri, majuscules, minuscules combined)
2. ``lectionary`` — group 4
3. ``section_e`` — non-lectionaries with ``section_e == 1`` (Gospels)
4. ``section_a`` — non-lectionaries with ``section_a == 1`` (Acts + Catholic Epistles)
5. ``section_p`` — non-lectionaries with ``section_p == 1`` (Pauline Epistles)
6. ``section_r`` — non-lectionaries with ``section_r == 1`` (Revelation)
"""

from __future__ import annotations

import logging
from collections.abc import Sequence
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

import numpy as np
import pandas as pd
from numpy.typing import NDArray

if TYPE_CHECKING:
    import torch

logger = logging.getLogger(__name__)


@dataclass
class ManuscriptSubset:
    """A named slice of the manuscript DataFrame with per-subset KDE resampling.

    Attributes
    ----------
    key : str
        Short identifier (e.g. ``"non_lectionary"``, ``"section_e"``).
    label : str
        Human-readable label used in plots and tables.
    frame : pd.DataFrame
        Subset of the manuscript DataFrame.  When created by
        :func:`build_manuscript_subsets`, the frame already contains a
        ``resampledYear`` column generated by a fresh per-subset KDE fit.
    """

    key: str
    label: str
    frame: pd.DataFrame


@dataclass
class SubsetFitResult:
    """Result of a birth-death MLE fit for one manuscript subset.

    Attributes
    ----------
    key : str
        Short identifier matching the :class:`ManuscriptSubset`.
    label : str
        Human-readable label.
    success : bool
        Whether the optimiser converged.
    n_manuscripts : int
        Total manuscripts in the subset (may be 0).
    times : torch.Tensor
        Adjusted epoch end times from
        ``BirthDeathProcess.adjusted_epoch_end_times``.
    ages : NDArray[np.float64]
        Manuscript ages (in years, relative to the last epoch end).
    nll_history : list[float]
        Negative log-likelihood history from the best optimiser attempt.
    log_likelihood : float
        Log-likelihood at the MLE, or ``-inf`` on failure.
    epoch_results : list[dict[str, Any]]
        Per-epoch result dicts (one per epoch).  Keys present on success:
        ``period``, ``start``, ``end``, ``n_manuscripts``, ``birth_rates``,
        ``death_rates``, ``half_life``, ``success``.  Optional keys when
        covariance is available: ``birth_rate_se``, ``death_rate_se``,
        ``birth_rate_ci``, ``death_rate_ci``.
    """

    key: str
    label: str
    success: bool
    n_manuscripts: int
    times: torch.Tensor
    ages: NDArray[np.float64]
    nll_history: list[float]
    log_likelihood: float
    epoch_results: list[dict[str, Any]] = field(default_factory=list)


def build_manuscript_subsets(
    df: pd.DataFrame,
    *,
    current_year: int = 2024,
) -> list[ManuscriptSubset]:
    """Build the six canonical NTVMR analysis subsets with independent resampling.

    Each subset frame is a ``.copy()`` of the relevant rows, then passed
    through :func:`~inf_bp_texts.data.data_cleaning.add_resampled_year_column`
    so it carries its own fresh KDE-resampled ``resampledYear`` column.

    Parameters
    ----------
    df : pd.DataFrame
        Cleaned manuscript DataFrame. Must contain: ``earlyYear``,
        ``lateYear``, ``group`` (int, values 1–4), ``section_e``,
        ``section_a``, ``section_p``, ``section_r`` (0/1 flags).
        ``midYear`` is computed if absent.
    current_year : int
        Reference year for the KDE resampler (default 2024).

    Returns
    -------
    list[ManuscriptSubset]
        Six subsets in canonical order (non-lectionary, lectionary,
        section_e, section_a, section_p, section_r).
    """
    from inf_bp_texts.data.data_cleaning import (  # noqa: PLC0415
        add_resampled_year_column,
    )

    # Ensure midYear is present for temporal sort inside add_resampled_year_column.
    if "midYear" not in df.columns:
        df = df.copy()
        df["midYear"] = (df["earlyYear"] + df["lateYear"]) / 2

    non_lect_mask: pd.Series[bool] = df["group"].isin([1, 2, 3])
    lect_mask: pd.Series[bool] = df["group"] == 4

    def _make(key: str, label: str, mask: pd.Series[bool]) -> ManuscriptSubset:
        frame = df.loc[mask].copy()
        if len(frame) >= 2:
            try:
                add_resampled_year_column(frame, current_year=current_year)
            except ValueError:
                # Zero-variance or near-degenerate date ranges: KDE cannot fit.
                # Fall back to midYear so fit_manuscript_subset can still attempt
                # inference (it will return success=False if rates are not finite).
                logger.warning(
                    "Subset %s: KDE resampling failed (n=%d, likely zero-variance"
                    " dates). Falling back to midYear.",
                    key,
                    len(frame),
                )
                frame["resampledYear"] = frame["midYear"].round().astype(np.int64)
        elif len(frame) == 1:
            # Single-manuscript subsets: midYear ≈ resampledYear
            frame["resampledYear"] = frame["midYear"].round().astype(np.int64)
        # Empty frames get no resampledYear column — fit will return success=False.
        return ManuscriptSubset(key=key, label=label, frame=frame)

    return [
        _make("non_lectionary", "Non-Lectionary (1–3)", non_lect_mask),
        _make("lectionary", "Lectionary (4)", lect_mask),
        _make("section_e", "Gospels (e)", non_lect_mask & (df["section_e"] == 1)),
        _make(
            "section_a",
            "Acts + Catholic Epistles (a)",
            non_lect_mask & (df["section_a"] == 1),
        ),
        _make(
            "section_p",
            "Pauline Epistles (p)",
            non_lect_mask & (df["section_p"] == 1),
        ),
        _make(
            "section_r",
            "Revelation (r)",
            non_lect_mask & (df["section_r"] == 1),
        ),
    ]


def fit_manuscript_subset(
    subset: ManuscriptSubset,
    epochs: Sequence[tuple[int, int, str]],
    *,
    start_time: int | float,
    age_column: str = "resampledYear",
    random_seed: int,
    **fit_kwargs: Any,
) -> SubsetFitResult:
    """Fit a birth-death process to one manuscript subset.

    Builds a :class:`~inf_bp_texts.models.BirthDeathProcess` from
    ``subset.frame[age_column]``, calls
    :func:`~inf_bp_texts.inference.fit_birth_death_processes`, then parses
    per-epoch rates, standard errors, and 95% confidence intervals (via the
    delta method on log-parameters).

    Parameters
    ----------
    subset : ManuscriptSubset
        Subset frame produced by :func:`build_manuscript_subsets`.
    epochs : Sequence[tuple[int, int, str]]
        Epoch definitions as ``(start, end, name)`` triples, e.g.
        ``MANUSCRIPT_EPOCHS_SIX_ERA`` for six-era fits or
        ``[(100, 2000, "100–2000 CE")]`` for a single epoch.
    start_time : int | float
        Epoch start year (calendar) — typically ``epochs[0][0]``.
    age_column : str
        Column in ``subset.frame`` holding the creation years (default
        ``"resampledYear"``).
    random_seed : int
        Random seed forwarded to
        :func:`~inf_bp_texts.inference.fit_birth_death_processes`.
    **fit_kwargs
        Additional keyword arguments forwarded to
        :func:`~inf_bp_texts.inference.fit_birth_death_processes`
        (e.g. ``optimizers``, ``optimizer_kwargs``, ``convergence_config``,
        ``perturb_initial_params_std``).

    Returns
    -------
    SubsetFitResult
        On convergence failure, ``success=False`` and ``epoch_results`` is
        empty.  The result never raises — all exceptions are caught and
        logged as warnings.
    """
    import torch  # noqa: PLC0415

    from inf_bp_texts.inference import (  # noqa: PLC0415
        confidence_intervals_from_log_covariance,
        fit_birth_death_processes,
    )
    from inf_bp_texts.models import BirthDeathProcess  # noqa: PLC0415

    frame = subset.frame
    n_total = len(frame)
    n_epochs = len(epochs)

    # Placeholder tensors for early returns
    _zero_times = torch.zeros(n_epochs, dtype=torch.float64)
    _empty_ages: NDArray[np.float64] = np.empty(0, dtype=np.float64)

    def _fail(
        msg: str,
        *,
        times: torch.Tensor | None = None,
        ages: NDArray[np.float64] | None = None,
        nll: list[float] | None = None,
    ) -> SubsetFitResult:
        logger.warning("Subset %s: %s", subset.key, msg)
        return SubsetFitResult(
            key=subset.key,
            label=subset.label,
            success=False,
            n_manuscripts=n_total,
            times=times if times is not None else _zero_times,
            ages=ages if ages is not None else _empty_ages,
            nll_history=nll or [],
            log_likelihood=float("-inf"),
        )

    # Guard: too few manuscripts or column missing
    if n_total < 2 or age_column not in frame.columns:
        return _fail(
            f"too few manuscripts ({n_total}) or missing column '{age_column}'"
        )

    # Build BirthDeathProcess
    try:
        creation_years: list[float] = frame[age_column].astype(float).tolist()
        bdp = BirthDeathProcess(
            creation_times=creation_years,
            epoch_end_times=[int(e[1]) for e in epochs],
            start_time=float(start_time),
        )
    except Exception as exc:
        return _fail(f"BirthDeathProcess construction failed: {exc}")

    ages_tensor: torch.Tensor = bdp.manuscript_ages
    times: torch.Tensor = bdp.adjusted_epoch_end_times
    ages_np: NDArray[np.float64] = ages_tensor.detach().cpu().numpy().astype(np.float64)

    # Per-epoch manuscript counts.  The last epoch uses an inclusive upper bound
    # so manuscripts dated exactly at the final year are not silently excluded.
    epoch_n: list[int] = [
        int(
            (
                (frame[age_column] >= e_start)
                & (
                    frame[age_column] <= e_end
                    if i == len(epochs) - 1
                    else frame[age_column] < e_end
                )
            ).sum()
        )
        for i, (e_start, e_end, _) in enumerate(epochs)
    ]

    # Run the fit
    try:
        result: dict[str, Any] = fit_birth_death_processes(
            list_of_ages=[ages_tensor.clone()],
            times=times,
            is_ordered=False,
            random_seed=random_seed,
            **fit_kwargs,
        )
    except Exception as exc:
        return _fail(
            f"fit_birth_death_processes raised: {exc}", times=times, ages=ages_np
        )

    # Extract nll_history from the best optimiser attempt
    opt: Any = result.get("optimization_result")
    attempts: list[Any] = opt.get("attempts", []) if isinstance(opt, dict) else []
    sel_idx: Any = opt.get("selected_attempt_index") if isinstance(opt, dict) else None
    selected: Any = None
    if isinstance(attempts, list) and attempts:
        if isinstance(sel_idx, int) and 0 <= sel_idx < len(attempts):
            selected = attempts[sel_idx]
        else:
            selected = attempts[0]
    nll_history: list[float] = (
        [float(v) for v in selected.get("nll_history", [])]
        if isinstance(selected, dict)
        else []
    )
    log_lik = float(result.get("log_likelihood", float("-inf")))

    if not result.get("success"):
        return SubsetFitResult(
            key=subset.key,
            label=subset.label,
            success=False,
            n_manuscripts=n_total,
            times=times,
            ages=ages_np,
            nll_history=nll_history,
            log_likelihood=log_lik,
        )

    # Parse per-epoch rates
    birth_rates_arr = np.atleast_1d(np.asarray(result["birth_rates"], dtype=float))
    death_rates_arr = np.atleast_1d(np.asarray(result["death_rates"], dtype=float))

    # Per-epoch uncertainty (delta method on log-parameters)
    birth_ses: np.ndarray | None = None
    death_ses: np.ndarray | None = None
    birth_cis: np.ndarray | None = None
    death_cis: np.ndarray | None = None
    uncertainty: Any = result.get("uncertainty")
    if uncertainty is not None:
        try:
            covariance_log = np.asarray(uncertainty, dtype=float)
            log_rates = np.log(np.concatenate([birth_rates_arr, death_rates_arr]))
            rate_jac = np.diag(np.concatenate([birth_rates_arr, death_rates_arr]))
            covariance_rates = rate_jac @ covariance_log @ rate_jac.T
            rate_ses = np.sqrt(np.clip(np.diag(covariance_rates), 0.0, None))
            rate_cis = (
                confidence_intervals_from_log_covariance(
                    torch.as_tensor(log_rates, dtype=torch.float64),
                    torch.as_tensor(covariance_log, dtype=torch.float64),
                )
                .cpu()
                .numpy()
            )
            birth_ses = rate_ses[:n_epochs]
            death_ses = rate_ses[n_epochs:]
            birth_cis = rate_cis[:n_epochs]
            death_cis = rate_cis[n_epochs:]
        except Exception as exc:
            logger.warning(
                "Could not compute uncertainties for subset %s: %s", subset.key, exc
            )

    # Build per-epoch result dicts
    epoch_results: list[dict[str, Any]] = []
    for i, (e_start, e_end, period_name) in enumerate(epochs):
        br = float(
            birth_rates_arr[i] if birth_rates_arr.size > 1 else birth_rates_arr[0]
        )
        dr = float(
            death_rates_arr[i] if death_rates_arr.size > 1 else death_rates_arr[0]
        )
        half_life = float(np.log(2) / dr) if dr > 0.0 else float("inf")
        entry: dict[str, Any] = {
            "period": period_name,
            "start": e_start,
            "end": e_end,
            "n_manuscripts": epoch_n[i],
            "birth_rates": br,
            "death_rates": dr,
            "half_life": half_life,
            "success": True,
        }
        if (
            birth_ses is not None
            and death_ses is not None
            and birth_cis is not None
            and death_cis is not None
        ):
            entry["birth_rate_se"] = float(birth_ses[i])
            entry["death_rate_se"] = float(death_ses[i])
            entry["birth_rate_ci"] = (float(birth_cis[i, 0]), float(birth_cis[i, 1]))
            entry["death_rate_ci"] = (float(death_cis[i, 0]), float(death_cis[i, 1]))
        epoch_results.append(entry)

    return SubsetFitResult(
        key=subset.key,
        label=subset.label,
        success=True,
        n_manuscripts=n_total,
        times=times,
        ages=ages_np,
        nll_history=nll_history,
        log_likelihood=log_lik,
        epoch_results=epoch_results,
    )
